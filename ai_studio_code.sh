# 1. Iniciar o repositório git (se ainda não tiver iniciado)
git init

# 2. Adicionar todos os arquivos necessários
git add .

# 3. Criar o commit
git commit -m "feat: landing page +250 jornais biologicos completa com pixels"

# 4. Renomear para a branch principal
git branch -M main

# 5. Conectar com seu repositório no GitHub (troque pela URL do seu repositório)
git remote add origin https://github.com/SEU_USUARIO/SEU_REPOSITORIO.git

# 6. Enviar para o GitHub
git push -u origin main